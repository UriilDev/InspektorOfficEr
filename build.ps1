#requires -Version 5.1
# build.ps1 : assembles src\*.ps1 into ONE portable Inspektor.ps1 (what goes onto the USB drive).
#   .\build.ps1            -> writes Inspektor.ps1 next to this script
#   .\build.ps1 -Check     -> builds in memory and fails (exit 1) if Inspektor.ps1 differs (CI drift check)
# The output is pure ASCII with CRLF line endings. Non-ASCII characters in sources are an error:
# write Cyrillic as \uXXXX through the U '...' helper.
param([switch]$Check, [string]$OutFile)

$ErrorActionPreference = 'Stop'
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
if (-not $OutFile) { $OutFile = Join-Path $here 'Inspektor.ps1' }

# order matters: Core and Context first, Main last
$parts = 'Core', 'Context', 'Report', 'Collectors', 'Passport', 'Xlsx', 'Inventory', 'Main'

$header = @'
#requires -Version 5.1
# InspektorOfficEr : PC inspection report (WMI) + inventory (AnyDesk, HopToDesk, disk-protection software, passport) -> Excel on the flash drive
# GENERATED FILE: edit src\*.ps1 and run build.ps1. Do not edit this file by hand.
# Switches: -SkipReport (inventory only)  -SkipExcel (report only)  -NoHopCli  -NoPrompt
param([switch]$SkipReport, [switch]$SkipExcel, [switch]$NoHopCli, [switch]$NoPrompt)

$ErrorActionPreference = 'Stop'

'@

$sb = New-Object Text.StringBuilder
[void]$sb.Append(($header -replace "`r?`n", "`r`n"))
foreach ($p in $parts) {
    $f = Join-Path (Join-Path $here 'src') ($p + '.ps1')
    if (-not (Test-Path -LiteralPath $f)) { throw "missing source: $f" }
    $t = [IO.File]::ReadAllText($f, [Text.Encoding]::UTF8).TrimStart([char]0xFEFF)
    if ($t -match '[^\x00-\x7F]') { throw "non-ASCII characters in $f (use \uXXXX via U '...')" }
    $t = ($t -replace "`r?`n", "`r`n").TrimEnd() + "`r`n`r`n"
    [void]$sb.Append($t)
}
$text = $sb.ToString().TrimEnd() + "`r`n"

# the result must parse
$errs = $null; $tok = $null
[void][System.Management.Automation.Language.Parser]::ParseInput($text, [ref]$tok, [ref]$errs)
if ($errs -and $errs.Count) { $errs | ForEach-Object { Write-Host ("parse error line {0}: {1}" -f $_.Extent.StartLineNumber, $_.Message) -ForegroundColor Red }; exit 2 }

if ($Check) {
    $cur = $(if (Test-Path -LiteralPath $OutFile) { [IO.File]::ReadAllText($OutFile) } else { '' })
    if ($cur -ne $text) { Write-Host "Inspektor.ps1 is out of date: run .\build.ps1" -ForegroundColor Red; exit 1 }
    Write-Host 'Inspektor.ps1 is up to date.'; exit 0
}
[IO.File]::WriteAllText($OutFile, $text, (New-Object Text.ASCIIEncoding))
Write-Host ("built {0} ({1} lines)" -f $OutFile, ($text -split "`r`n").Count)
